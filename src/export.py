def _courses_process_lang(
	entry: dict,
	page_fetch_lang: str,
	table_name: str
) -> tuple[int, str]:
	"""
	Indices for de/en language dicts differ! -> select using "page_fetch_lang"
	"""
	lang_entry = entry[page_fetch_lang]
	keys = _FIELD_KEYS[page_fetch_lang]

	non_empty_count = 0
	def get(field):
		nonlocal non_empty_count
		value = lang_entry.get(keys[field]) or ""
		if value:
			non_empty_count += 1
		return value

	course_number    = lang_entry.get("course_number", "")
	course_title     = lang_entry.get("course_title", "")
	semester         = lang_entry.get("course_semester", "")
	course_type      = lang_entry.get("course_type", "")
	course_sws       = lang_entry.get("course_hours", "")
	course_ECTS      = lang_entry.get("course_ECTS", "")
	additional_info  = lang_entry.get("course_add_info", "") or ""

	properties       = get("properties")
	more_info        = get("more_info")
	subj_of_course   = get("subj_of_course")
	methods          = get("methods")
	examination_mode = get("exam_mode")
	exam_modalities  = get("exam_modalities")
	course_reg       = get("course_reg")
	literatur        = get("literatur")
	prev_knowledge   = get("prev_knowledge")
	preced_courses   = get("preced_courses")
	lecturers        = _extract_lecturers(get("lecturers"))
	language         = get("language")
	institute        = get("institute")
	group_dates      = get("group_dates")
	exams            = get("exams")
	group_reg        = get("group_reg")
	course_dates     = get("course_dates")
	curricula        = str(_extract_curricula(get("curricula")))
	aim_of_course    = get("aim_of_course")
	learning_outcome = get("learning_outcome")

	sql = (
		f"INSERT IGNORE INTO `{table_name}` "
		f"(`page_fetch_lang`, `course_number`, `course_title`, "
		f"`semester`, `type`, `sws`, `ECTS`, `add_info`, "
		f"`Merkmale`, `Weitere Informationen`, `Inhalt der Lehrveranstaltung`, "
		f"`Methoden`, `Prüfungsmodus`, `Leistungsnachweis`, `LVA_Anmeldung`, `Literatur`, "
		f"`Vorkenntnisse`, `Vorausgehende Lehrveranstaltungen`, `Vortragende Personen`, "
		f"`Sprache`, `Institut`, `Gruppentermine`, `Prüfungen`, `Gruppen_Anmeldung`, "
		f"`LVA Termine`, `Curricula`, `Ziele der Lehrveranstaltung`, `Lernergebnisse`) "
		f"VALUES ("
		f"'{page_fetch_lang}', '{course_number}', '{course_title}', '{semester}', "
		f"'{course_type}', '{course_sws}', '{course_ECTS}', '{additional_info}', "
		f"'{properties}', '{more_info}', '{subj_of_course}', '{methods}',"
		f"'{examination_mode}', '{exam_modalities}', '{course_reg}',"
		f"'{literatur}', '{prev_knowledge}', '{preced_courses}', '{lecturers}',"
		f"'{language}', '{institute}', '{group_dates}', '{exams}',"
		f"'{group_reg}', '{course_dates}', '{curricula}', '{aim_of_course}',"
		f"'{learning_outcome}'"
		f");"
	)

	return non_empty_count, sql


