def _load_config(config_file: str) -> dict:
	with open(config_file) as f:
		return yaml.safe_load(f)


def _escape(value: str) -> str:
	"""Escape single quotes for MySQL."""
	return value.replace("'", "\\'")


def _build_unique_id(entry: dict) -> str:
	return (
		entry["subsemester"]
		+ entry["semester"]
		+ entry["subprogram_title_de"]
		+ entry["academic_program_de"]
	)


def export_study_programs(dict_studyprograms: dict, output_path: Path) -> None:
	lines = []
	lines.append("-- Study programs export")
	lines.append("-- Generated by export.py\n")

	for key, entry in dict_studyprograms.items():
		unique_id      = _escape(_build_unique_id(entry))
		course_numbers = _escape("|".join(entry.get("course_numbers", [])))
		semester       = _escape(entry.get("semester", ""))
		subsemester    = _escape(entry.get("subsemester", ""))
		subprogram_de  = _escape(entry.get("subprogram_title_de", ""))
		subprogram_en  = _escape(entry.get("subprogram_title_en", ""))
		academic_de    = _escape(entry.get("academic_program_de", ""))
		academic_en    = _escape(entry.get("academic_program_en", ""))
		program_code   = _escape(entry.get("program_code", ""))

		sql = (
			f"INSERT IGNORE INTO `overview` "
			f"(`unique_id`, `course_numbers`, `semester`, `subsemester`, "
			f"`subprogram_title_de`, `subprogram_title_en`, "
			f"`academic_program_de`, `academic_program_en`, `program_code`) "
			f"VALUES ("
			f"'{unique_id}', '{course_numbers}', '{semester}', '{subsemester}', "
			f"'{subprogram_de}', '{subprogram_en}', "
			f"'{academic_de}', '{academic_en}', '{program_code}'"
			f");"
		)
		lines.append(sql)

	output_path.parent.mkdir(parents=True, exist_ok=True)
	output_path.write_text("\n".join(lines), encoding="utf-8")
	logging.getLogger(__name__).info(f"Wrote {len(dict_studyprograms)} rows to {output_path}")


